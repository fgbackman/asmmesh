    LEAVE 0

// void Lpcopy(dst, src, n) — bytes, forwards (leaf: x9, x10)
Lpcopy:
    mov  x9, #0
1:  cmp  x9, x2
    b.hs 2f
    ldrb w10, [x1, x9]
    strb w10, [x0, x9]
    add  x9, x9, #1
    b    1b
2:  ret

// long _bc_ann_make(const uint8 *nick, long nlen, const uint8 xpub[32], const uint8 edpub[32],
//   uint8 *out) -> the announce payload's length: our name (cut to BT_NICK_SEND bytes: see
//   bc_defs.inc) and our two keys
.globl _bc_ann_make
_bc_ann_make:
    ENTER 0
    mov  x19, x0
    mov  x20, x2
    mov  x21, x3
    mov  x22, x4
    mov  x2, #BT_NICK_SEND
    bl   _bc_utf8_cut
    mov  x23, x0
    mov  w9, #1
    strb w9, [x22]
    strb w23, [x22, #1]
    add  x0, x22, #2
    mov  x1, x19
    mov  x2, x23
    bl   Lpcopy
    add  x24, x22, x23
    add  x24, x24, #2
    mov  w9, #2
    strb w9, [x24]
    mov  w9, #32
    strb w9, [x24, #1]
    add  x0, x24, #2
    mov  x1, x20
    mov  x2, #32
    bl   Lpcopy
    add  x24, x24, #34
    mov  w9, #3
    strb w9, [x24]
    mov  w9, #32
    strb w9, [x24, #1]
    add  x0, x24, #2
    mov  x1, x21
    mov  x2, #32
    bl   Lpcopy
    add  x0, x23, #70
    LEAVE 0

// long _bc_ann_read(const uint8 *p, long n, uint8 *an) -> 0, an filled (AN_*), or -1 if it
//   isn't an announce we can use. As bitchat: TLVs in any order, the last of a kind wins,
//   unknown kinds are skipped, a TLV running past the end spoils it all.
.globl _bc_ann_read
_bc_ann_read:
    ENTER 0
    mov  x19, x0
    mov  x20, x1
    mov  x21, x2
    stp  xzr, xzr, [x21]
    stp  xzr, xzr, [x21, #16]
    mov  x22, #0                          // where we are
1:  add  x9, x22, #2
    cmp  x9, x20
    b.hi 6f
    ldrb w10, [x19, x22]                  // kind
    add  x11, x19, x22
    ldrb w24, [x11, #1]                   // length
    add  x23, x19, x9                     // value
    add  x22, x9, x24
    cmp  x22, x20
    b.hi 9f
    cmp  w10, #1
    b.eq 2f
    cmp  w10, #2
    b.eq 3f
    cmp  w10, #3
    b.eq 4f
    b    1b
2:  mov  x0, x23                          // a name: only if it's real UTF-8
    mov  x1, x24
    bl   _bc_utf8_ok
    cmp  x0, #0
    csel x9, x23, xzr, ne
    str  x9, [x21, #AN_NICK]
    str  x24, [x21, #AN_NLEN]
    b    1b
3:  cmp  x24, #32
    csel x9, x23, xzr, eq
    str  x9, [x21, #AN_XPUB]
    b    1b
4:  cmp  x24, #32
    csel x9, x23, xzr, eq
    str  x9, [x21, #AN_EDPUB]
    b    1b
6:  ldr  x9, [x21, #AN_NICK]
    cbz  x9, 9f
    ldr  x9, [x21, #AN_XPUB]
    cbz  x9, 9f
    ldr  x9, [x21, #AN_EDPUB]
    cbz  x9, 9f
    mov  x0, #0
    LEAVE 0
9:  mov  x0, #-1
    LEAVE 0

// long Lfind(tab, uint64 id) -> the slot holding that peer, or -1 (leaf)
Lfind:
    mov  x9, #0
1:  cmp  x9, #BT_N
    b.hs 2f
    add  x10, x0, x9, lsl #BT_SHIFT
    ldr  x11, [x10, #BT_HEARD]
    cbz  x11, 3f
    ldr  x11, [x10, #BT_ID]
    cmp  x11, x1
    b.eq 4f
3:  add  x9, x9, #1
    b    1b
2:  mov  x0, #-1
    ret
4:  mov  x0, x9
    ret

// long _bc_peer_heard(tab, long now_ms, const uint8 own_id[8], const uint8 *dp, uint8 *scratch,
//   long cap, pins or 0) -> the person's slot, with x1 = 1 if they're new; or why not: -1 not
//   an announce we can read, -2 its sender isn't its key's id, -3 it's ours, -4 older than
//   15 minutes, over 5 minutes ahead, or not later than one taken before (a recording played
//   back), -5 not signed by the key it announces, or a weak key, -6 another signing key than
//   the one we have for them (now, or pinned long ago), -9 the table is full of people heard
//   in the last 30 s, -10 more new people this minute than PN_NEW. A new person takes a free
//   slot, or the one heard from longest ago if that's over 30 s: a flood of made-up
//   people can't push out the real ones around.
.globl _bc_peer_heard
_bc_peer_heard:
    ENTER 112                             // [96] announce (AN_SIZE) [128] SHA-256 [160] scratch
    mov  x19, x0                          //   [168] cap [176] our id [184] pins [192] their pin
    mov  x20, x1
    mov  x21, x3
    str  x4, [sp, #160]
    str  x5, [sp, #168]
    str  x6, [sp, #184]
    str  xzr, [sp, #192]
    ldr  x9, [x2]
    str  x9, [sp, #176]
    ldr  x9, [x21, #DP_TYPE]
    cmp  x9, #0x01
    b.ne Lph_no
    ldr  x0, [x21, #DP_PAY]
    ldr  x1, [x21, #DP_PLEN]
    add  x2, sp, #96
    bl   _bc_ann_read
    tbnz x0, #63, Lph_no
    ldr  x0, [sp, #96 + AN_XPUB]          // its id must come from its Noise key
    mov  x1, #32
    add  x2, sp, #128
    bl   _bc_sha256
    ldr  x9, [sp, #128]
    ldr  x10, [x21, #DP_SENDER]
    ldr  x22, [x10]                       // x22: the id
    cmp  x9, x22
    b.ne Lph_mismatch
    ldr  x9, [sp, #176]
    cmp  x9, x22
    b.eq Lph_self
    mov  x9, #(BT_STALE & 0xffff)         // not older than 15 minutes
    movk x9, #(BT_STALE >> 16), lsl #16
    cmp  x20, x9
    b.lo 1f
    sub  x9, x20, x9
    ldr  x10, [x21, #DP_TS]
    cmp  x10, x9
    b.lo Lph_stale
1:  mov  x9, #(BT_FUTURE & 0xffff)        // nor over 5 minutes ahead
    movk x9, #(BT_FUTURE >> 16), lsl #16
    add  x9, x20, x9
    ldr  x10, [x21, #DP_TS]
    cmp  x10, x9
    b.hi Lph_stale
    ldr  x0, [sp, #96 + AN_EDPUB]         // a weak key proves nothing
    bl   _bc_ed_small
    cbnz x0, Lph_badsig
    mov  x0, x19
    mov  x1, x22
    bl   Lfind
    mov  x23, x0                          // x23: their slot, or -1
    tbnz x23, #63, 2f
    add  x0, x19, x23, lsl #BT_SHIFT      // known: the signing key must be the same
    add  x0, x0, #BT_EDPUB
    ldr  x1, [sp, #96 + AN_EDPUB]
