// long _bc_utf8_ok(const uint8 *p, long n) -> 1 if it's well-formed UTF-8 (no overlong
//   forms, surrogates or code points past U+10FFFF), else 0 (leaf)
.globl _bc_utf8_ok
_bc_utf8_ok:
    mov  x9, #0
1:  cmp  x9, x1
    b.hs 8f
    ldrb w10, [x0, x9]
    cmp  w10, #0x80
    b.hs 2f
    add  x9, x9, #1
    b    1b
2:  mov  w11, #0x80                       // second byte: from w11 to w12
    mov  w12, #0xbf
    cmp  w10, #0xc2
    b.lo 9f
    mov  x13, #1                          // continuation bytes
    cmp  w10, #0xe0
    b.lo 4f
    mov  x13, #2
    cmp  w10, #0xf0
    b.hs 3f
    cmp  w10, #0xe0
    b.ne 21f
    mov  w11, #0xa0
21: cmp  w10, #0xed
    b.ne 4f
    mov  w12, #0x9f
    b    4f
3:  mov  x13, #3
    cmp  w10, #0xf4
    b.hi 9f
    b.ne 31f
    mov  w12, #0x8f
31: cmp  w10, #0xf0
    b.ne 4f
    mov  w11, #0x90
4:  add  x14, x9, x13                     // all of it must be there
    cmp  x14, x1
    b.hs 9f
    add  x9, x9, #1
    ldrb w10, [x0, x9]
    cmp  w10, w11
    b.lo 9f
    cmp  w10, w12
    b.hi 9f
5:  subs x13, x13, #1
    b.eq 6f
    add  x9, x9, #1
    ldrb w10, [x0, x9]
    and  w10, w10, #0xc0
    cmp  w10, #0x80
    b.ne 9f
    b    5b
6:  add  x9, x9, #1
    b    1b
8:  mov  x0, #1
    ret
9:  mov  x0, #0
    ret

// long _bc_utf8_cut(const uint8 *p, long n, long max) -> at most max bytes of p, cut
//   before a character rather than inside one (leaf)
.globl _bc_utf8_cut
_bc_utf8_cut:
    cmp  x1, x2
    csel x2, x1, x2, lo
1:  cbz  x2, 2f
    cmp  x2, x1
    b.hs 2f
    ldrb w9, [x0, x2]
    and  w9, w9, #0xc0
    cmp  w9, #0x80
    b.ne 2f
    sub  x2, x2, #1
    b    1b
2:  mov  x0, x2
    ret

// void _bc_text_clean(uint8 *dst, const uint8 *src, long n) — a bitchat name or message as
//   it may be shown: control characters (C0, DEL, C1 with U+0085), line and paragraph
//   separators, direction marks, embeddings, overrides and isolates, and invisible format
//   characters (U+00AD, U+061C, U+180E, U+200B-F, U+2028-E, U+2060-4, U+2066-F, U+FEFF,
//   U+FFF9-B) become spaces, byte for byte, so nobody can start a fake line, turn text
//   around or hide part of it. dst may be src (leaf)
.globl _bc_text_clean
_bc_text_clean:
    mov  x9, #0
    mov  w15, #' '
1:  cmp  x9, x2
    b.hs 9f
    ldrb w10, [x1, x9]
    cmp  w10, #0x20
    b.lo 7f
    cmp  w10, #0x7f
    b.eq 7f
    add  x11, x9, #1                      // two bytes: C1 controls, soft hyphen, ALM
    cmp  x11, x2
    b.hs 2f
    ldrb w12, [x1, x11]
    cmp  w10, #0xc2
    b.ne 21f
    cmp  w12, #0xad
    b.eq 62f
    sub  w13, w12, #0x80
    cmp  w13, #0x1f
    b.ls 62f
    b    22f
21: cmp  w10, #0xd8
    b.ne 22f
    cmp  w12, #0x9c
    b.eq 62f
22: add  x11, x9, #2                      // three bytes: Lblank3
    cmp  x11, x2
    b.hs 2f
    ldrb w13, [x1, x11]
    ADRL x14, Lblank3
3:  ldrb w16, [x14]
    cbz  w16, 2f
    ldrb w17, [x14, #1]
    cmp  w10, w16
    ccmp w12, w17, #0, eq
    b.ne 4f
    ldrb w16, [x14, #2]
    ldrb w17, [x14, #3]
    cmp  w13, w16
    ccmp w13, w17, #2, hs                 // (below the range: force "hi")
    b.ls 63f
4:  add  x14, x14, #4
    b    3b
2:  strb w10, [x0, x9]                    // as it is
    add  x9, x9, #1
    b    1b
63: strb w15, [x0, x9]
    add  x9, x9, #1
62: strb w15, [x0, x9]
    add  x9, x9, #1
7:  strb w15, [x0, x9]
    add  x9, x9, #1
    b    1b
9:  ret

// long _bc_name_skel(uint8 *dst, const uint8 *src, long n) -> its length: what a name looks
//   like, to compare names: blanks, controls and invisible characters gone, letters that
//   pass for Latin ones (Cyrillic, Greek, fullwidth) as the Latin letter, case folded, and
//   0 as o, 1 l | ! as i (leaf)
.globl _bc_name_skel
_bc_name_skel:
    mov  x9, #0
    mov  x16, #0
1:  cmp  x9, x2
    b.hs 9f
    ldrb w10, [x1, x9]
    cmp  w10, #0x20
    b.ls 11f
    cmp  w10, #0x7f
    b.eq 11f
    cmp  w10, #0x80
    b.hs 3f
    sub  w11, w10, #'A'                   // ASCII: lower case, then the look-alikes
    cmp  w11, #25
    b.hi 2f
    add  w10, w10, #32
2:  cmp  w10, #'0'
    mov  w11, #'o'
    csel w10, w11, w10, eq
    mov  w11, #'i'
    cmp  w10, #'1'
    csel w10, w11, w10, eq
    cmp  w10, #'l'
    csel w10, w11, w10, eq
    cmp  w10, #'|'
    csel w10, w11, w10, eq
    cmp  w10, #'!'
    csel w10, w11, w10, eq
    b    8f
3:  add  x11, x9, #1
    cmp  x11, x2
    b.hs 8f
    ldrb w12, [x1, x11]
    cmp  w10, #0xc2                       // invisible two-byte ones: C1, nbsp, soft hyphen
    b.ne 31f
    cmp  w12, #0xa0
    b.eq 12f
    cmp  w12, #0xad
    b.eq 12f
    sub  w13, w12, #0x80
    cmp  w13, #0x1f
    b.ls 12f
31: cmp  w10, #0xd8                       //   ALM
    b.ne 32f
    cmp  w12, #0x9c
    b.eq 12f
32: cmp  w10, #0xcd                       //   combining grapheme joiner
    b.ne 33f
    cmp  w12, #0x8f
    b.eq 12f
33: ADRL x14, Lhomo2                      // a look-alike letter
34: ldrb w13, [x14]
    cbz  w13, 4f
    ldrb w15, [x14, #1]
    cmp  w10, w13
    ccmp w12, w15, #0, eq
    b.eq 35f
    add  x14, x14, #3
    b    34b
35: ldrb w10, [x14, #2]
    strb w10, [x0, x16]
    add  x16, x16, #1
    add  x9, x9, #2
    b    1b
4:  add  x11, x9, #2                      // three bytes
    cmp  x11, x2
    b.hs 8f
    ldrb w13, [x1, x11]
    ADRL x14, Lblank3
41: ldrb w15, [x14]
    cbz  w15, 5f
    ldrb w17, [x14, #1]
    cmp  w10, w15
    ccmp w12, w17, #0, eq
    b.ne 42f
    ldrb w15, [x14, #2]
    ldrb w17, [x14, #3]
    cmp  w13, w15
    ccmp w13, w17, #2, hs
    b.ls 13f
42: add  x14, x14, #4
    b    41b
5:  cmp  w10, #0xef                       // fullwidth A-Z, a-z
    b.ne 8f
    cmp  w12, #0xbc
    b.ne 51f
    sub  w15, w13, #0xa1
    cmp  w15, #25
    b.hi 8f
    b    52f
51: cmp  w12, #0xbd
    b.ne 8f
    sub  w15, w13, #0x81
    cmp  w15, #25
    b.hi 8f
52: add  w15, w15, #'a'
    mov  w17, #'i'
    cmp  w15, #'l'
    csel w15, w17, w15, eq
    strb w15, [x0, x16]
    add  x16, x16, #1
    add  x9, x9, #3
    b    1b
8:  strb w10, [x0, x16]                   // as it is
    add  x16, x16, #1
11: add  x9, x9, #1
    b    1b
12: add  x9, x9, #2
    b    1b
13: add  x9, x9, #3
    b    1b
9:  mov  x0, x16
    ret

// long _bc_name_same(const uint8 *a, long an, const uint8 *b, long bn) -> 1 if the two
//   names look alike (_bc_name_skel), else 0. Up to 100 bytes of each.
.globl _bc_name_same
_bc_name_same:
    ENTER 224                             // [96] a's skeleton [208] b's
    mov  x19, x2
    mov  x20, x3
    cmp  x1, #100
    mov  x9, #100
    csel x2, x1, x9, lo
    mov  x1, x0
    add  x0, sp, #96
    bl   _bc_name_skel
    mov  x21, x0
    cmp  x20, #100
    mov  x9, #100
    csel x2, x20, x9, lo
    mov  x1, x19
    add  x0, sp, #208
    bl   _bc_name_skel
    cmp  x0, x21
    b.ne 1f
    add  x0, sp, #96
    add  x1, sp, #208
    mov  x2, x21
    bl   _bc_memeq
    LEAVE 224
1:  mov  x0, #0
    LEAVE 224

// long _bc_ed_small(const uint8 pub[32]) -> 1 if it's an Ed25519 key of small order (or
//   its non-canonical twin): signatures under it prove nothing, so it's refused (leaf)
.globl _bc_ed_small
_bc_ed_small:
    ADRL x9, Lsmall
    mov  x10, #7
1:  mov  x11, #0
2:  ldrb w12, [x0, x11]
    cmp  x11, #31
    b.ne 3f
    and  w12, w12, #0x7f                  // the sign bit doesn't count
3:  ldrb w13, [x9, x11]
    cmp  w12, w13
    b.ne 4f
    add  x11, x11, #1
    cmp  x11, #32
    b.lo 2b
    mov  x0, #1
    ret
4:  add  x9, x9, #32
    subs x10, x10, #1
    b.ne 1b
    mov  x0, #0
    ret

// uint8 *_bc_pin_find(pins, uint64 id) -> its pin, or 0 (leaf)
.globl _bc_pin_find
_bc_pin_find:
    add  x9, x0, #PN_HDR
    mov  x10, #0
1:  cmp  x10, #PN_N
    b.hs 3f
    ldr  x11, [x9, #PN_HEARD]
    cbz  x11, 2f
    ldr  x11, [x9, #PN_ID]
    cmp  x11, x1
    b.eq 4f
2:  add  x9, x9, #PN_ESIZE
    add  x10, x10, #1
    b    1b
3:  mov  x0, #0
    ret
4:  mov  x0, x9
    ret

// void _bc_pin_note(pins, uint64 id, const uint8 edpub[32], long ts, long now_ms) — their
