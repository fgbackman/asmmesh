// bc_peer.s — who's around on bitchat (docs/bitchat_roadmap.md, Milestone 1): announces
// made and read, and the table of bitchat people heard. Pure, like bc_packet.s, so it runs
// under qemu; bc_ble.s does the radio, the clock and the Keychain.
//
// Ported from bitchat 04995f6: AnnouncementPacket (Packets.swift), BLEAnnouncePreflightPolicy,
// BLEAnnounceTrustPolicy, BLEPacketFreshnessPolicy and handleLeave (BLEService.swift).
//
//   announce (type 0x01) payload, TLVs of type(1) length(1) value:
//     0x01 nickname (UTF-8)   0x02 Noise static key (X25519, 32)   0x03 signing key (Ed25519, 32)
//     0x04 neighbours, 0x05 capabilities, 0x06 bridge cell: optional; unknown ones are skipped
//   leave (type 0x03): empty payload, signed
//
// An announce counts only if: the sender id is the first 8 bytes of SHA-256 of its Noise key,
// it isn't ours, it's under 15 minutes old, and it's signed by the signing key it announces.
// That signing key is then pinned: an announce from the same id with another key is refused.
// A leave counts only if signed with the pinned key. Everything here stays behind the wall:
// these are names and keys to show, nothing more.
//
// Stricter than bitchat: both keys must be 32 bytes (bitchat would read other lengths, and
// then fail the signature check anyway).

