    mov  x21, x2
    mov  x22, x3
    mov  x23, x4
    bl   _bc_pin_find
    cbnz x0, 5f
    add  x9, x19, #PN_HDR                 // new: a free pin, or the least lately heard
    mov  x10, #0
    mov  x24, x9
    mov  x12, #-1
1:  cmp  x10, #PN_N
    b.hs 4f
    ldr  x11, [x9, #PN_HEARD]
    cbz  x11, 3f
    cmp  x11, x12
    b.hs 2f
    mov  x12, x11
    mov  x24, x9
2:  add  x9, x9, #PN_ESIZE
    add  x10, x10, #1
    b    1b
3:  mov  x24, x9
4:  mov  x0, x24
    mov  x1, #PN_ESIZE
    bl   Lpzero
    str  x20, [x24, #PN_ID]
    add  x0, x24, #PN_ED
    mov  x1, x21
    mov  x2, #32
    bl   Lpcopy
    mov  x0, x24
5:  ldr  x9, [x0, #PN_FLOOR]
    cmp  x22, x9
